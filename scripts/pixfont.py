FW, FH = 5, 7

def glyph(ch):
    c = ch.upper()
    return F.get(c, F['?'])

def text_width(s, scale=1, tracking=1):
    if not s: return 0
    return (len(s) * (FW + tracking) - tracking) * scale

def text_runs(x, y, s, scale=1, tracking=1):
    """Yield (x, y, w, h) rects in grid units, merging horizontal runs."""
    cx = x
    for ch in s:
        rows = glyph(ch)
        for ry, row in enumerate(rows):
            rx = 0
            while rx < FW:
                if row[rx] == '#':
                    run = 1
                    while rx + run < FW and row[rx + run] == '#':
                        run += 1
                    yield (cx + rx * scale, y + ry * scale, run * scale, scale)
                    rx += run
                else:
                    rx += 1
        cx += (FW + tracking) * scale
